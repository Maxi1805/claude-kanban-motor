/** Por qué se excluyó un archivo (o, para `dependency-tree`, un directorio). */
export type ExclusionReason =
  /**
   * Un árbol que una herramienta de paquetes/build escribe y posee. Lo decide
   * el walk podando el directorio entero — ver el docstring del módulo.
   */
  | "dependency-tree"
  /** El NOMBRE lo fija un generador de código (sufijo obligatorio de la herramienta). */
  | "generated-name"
  /** El CONTENIDO se declara generado en su cabecera (marca convencional). */
  | "generated-marker"
  /** La FORMA del texto es de salida de un minificador, no de código escrito a mano. */
  | "minified-shape"
  /**
   * D-TEST — árbol o archivo de test, por una de dos vías, las dos con
   * criterio de admisión escrito: (a) el nombre de DIRECTORIO/archivo que la
   * propia herramienta de test busca por defecto o exige para descubrir el
   * archivo (Maven/Gradle, RSpec, Minitest, pytest, Jest/Vitest, el compilador
   * de Go), podado por directorio igual que `dependency-tree` cuando aplica; o
   * (b) —el hueco que este módulo no cubría— un DESCRIPTOR DE PROYECTO .NET
   * (`.csproj`/`.fsproj`/`.vbproj`) que referencia `Microsoft.NET.Test.Sdk`, el
   * paquete que `dotnet test`/VSTest exige para reconocer el proyecto como
   * ejecutable-de-test, sea cual sea el framework de aserciones que use por
   * encima. Ver la sección 4 y 5 del archivo.
   */
  | "test-tree"
  /**
   * N10/P11 — el archivo declara en su propia CABECERA una atribución de
   * autoría distinta de la que declara la abrumadora mayoría de los archivos
   * del mismo repo: una copia traída de afuera y pegada adentro. Es la
   * categoría que el docstring de este módulo declara desde D5 ("un árbol
   * `third_party/` copiado de upstream") y que hasta esta ola sólo se cubría
   * cuando el copista había tenido la gentileza de ponerle a la carpeta uno de
   * los nombres de `SKIP_DIRS` — es decir, casi nunca: la copia de
   * `text/template`+`html/template` de la stdlib de Go que hugo tiene adentro
   * vive en `tpl/internal/go_templates/`, y son 31 de los 34 archivos que el
   * criterio saca de ese repo. Ver la sección 6.
   */
  | "vendored-provenance";

export interface Exclusion {
  reason: ExclusionReason;
  /** Qué se observó, concreto, para poder auditar una exclusión sin releer el archivo. */
  detail: string;
}

export interface ExcludedFile extends Exclusion {
  /**
   * Ruta relativa al repo. Es un archivo salvo cuando `reason` es
   * `dependency-tree`, donde es el directorio podado (los archivos de adentro
   * nunca se visitan, así que no hay nada más específico que reportar).
   */
  path: string;
}

