/**
 * Exclusión de código vendorizado, generado, minificado y de ÁRBOL DE TEST —
 * D5 del registro (vendorizado/generado/minificado, implementado con efecto
 * medido cero por falta de corpus) más D-TEST (árbol de test, esta ola, con
 * corpus y con efecto medido).
 *
 * QUÉ PROBLEMA RESUELVE, LAS DOS MITADES. El analizador trata todo archivo con
 * una extensión conocida como código del usuario. No siempre lo es:
 *   · Un `.js` minificado de 200 KB en una sola línea, un `.pb.go` escupido
 *     por protoc y un árbol `third_party/` copiado de upstream (D5) producen
 *     hallazgos que nadie puede accionar (no se edita código generado: se
 *     regenera) y envenenan las métricas agregadas y las consultas de grafo.
 *   · Un archivo de test (D-TEST) no es generado ni vendorizado — lo escribió
 *     una persona — pero repite a propósito la misma forma cientos de veces
 *     (un `describe`/`it`/`[Fact]` por caso) y eso hace que la duplicación
 *     estructural y las hipótesis de patrón que cuelgan de ella (Composite,
 *     Facade, Template Method…) traten el árbol de test como si fuera una
 *     jerarquía de dominio o una fachada de producción que alguien puentea.
 *     Medido sobre el corpus de 8 lenguajes: el 52 % de las hipótesis vivas de
 *     newtonsoft-json colgaban de `Newtonsoft.Json.Tests/` antes de esta ola —
 *     ver la sección 4-5 más abajo para el mecanismo y el número después.
 *
 * LA REGLA QUE GOBIERNA ESTE ARCHIVO — y la razón de que casi todo comentario
 * de acá abajo sea una justificación y no una descripción: **está prohibido
 * resolver esto con una lista de nombres de proyecto o de librería**. Nada de
 * `jquery.min.js`, nada de "los dos archivos de jekyll", nada de "el árbol se
 * llama `Newtonsoft.Json.Tests`". Cada criterio de acá tiene que ser una
 * propiedad ESTRUCTURAL del formato — algo que sea verdad porque una
 * herramienta escribió el archivo o porque otra herramienta lo BUSCA con ese
 * criterio por defecto, no porque el repo se llame como se llama. Donde hay un
 * literal (`.pb.go`, `DO NOT EDIT`, `Microsoft.NET.Test.Sdk`) es porque ese
 * literal lo FIJA o lo EXIGE la herramienta, no el proyecto que lo consume, y
 * eso queda escrito entrada por entrada, con su RECHAZADO al lado cuando la
 * tentación de admitir un nombre parecido pero no fijado por ninguna
 * herramienta ya se evaluó y se descartó. Un criterio que no se pueda
 * justificar así no entra.
 *
 * REQUISITO DE SEGURIDAD, más fuerte que el de cobertura: excluir código
 * legítimo del usuario es un bug; dejar pasar un archivo vendorizado o de test
 * es ruido. Ante la duda, NO se excluye. Por eso hay entradas explícitamente
 * RECHAZADAS con el motivo escrito (`bin`, `packages`, `lib` en `SKIP_DIRS`;
 * `do not modify` y `generated by` a secas y `Test(s).ext` suelto acá abajo):
 * son las que un criterio "razonable" pero laxo se llevaría puestas.
 *
 * POR QUÉ ALGUNOS CRITERIOS NO VIVEN ACÁ. Las categorías 1-3 (D5) y 5
 * (D-TEST, proyecto .NET) son POR ARCHIVO O POR DESCRIPTOR: hay que ver el
 * nombre o el contenido de cada uno. Las categorías "árbol de dependencias" y
 * "directorio de test por nombre" (`spec`, `test`, `tests`, `__tests__`, y
 * `features` con su chequeo estructural aparte — sección 4b) son por
 * DIRECTORIO, y su valor está en no visitar el árbol: podar cuesta una
 * comparación, clasificar archivo por archivo cuesta exactamente lo que se
 * quería evitar. Por eso esas dos podan en el walk de `collectFiles`
 * (`SKIP_DIRS` para dependencias; `isTestDirName`/`isFeaturesDirName` de este
 * módulo para test, invocado desde `code-analyzer.ts`) y no hacen la poda
 * ellas mismas acá — pero el PREDICADO de test-por-nombre sí vive acá (
 * `isTestDirName`/`isFeaturesDirName`/`excludedGherkinFeaturesDir`/
 * `excludedByTestFilePattern`), junto a sus hermanos, para que un solo
 * archivo declare y justifique las seis categorías. La sexta (procedencia
 * ajena, N10/P11) es la única que NO se contesta mirando un solo archivo
 * —compara contra un estadístico del repo entero— y por eso la ingesta la
 * resuelve en dos fases sin leer nada de más; ver la sección 6. El tipo
 * {@link ExclusionReason} nombra las dos igual, porque el recorrido reporta
 * las podas para que la medición del frente pueda contarlas.
 *
 * DÓNDE SE APLICA. En la ingesta (`collectFiles` de `code-analyzer.ts`), que
 * es el único punto por el que un archivo entra al análisis. Excluir acá
 * significa que el archivo no produce `FileFacts`, no aporta nodos ni aristas
 * al grafo y no cuenta en el censo — no que se filtre después.
 */
