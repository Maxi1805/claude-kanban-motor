const REPO_ROOT = path.resolve(import.meta.dirname, "..", "..", "..");

const created: string[] = [];

/** Escribe `files` (ruta relativa → contenido) bajo un tmpdir fresco. */
async function makeTree(files: Record<string, string>): Promise<string> {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), "ck-ingest-excl-")));
  created.push(root);
  for (const [rel, contents] of Object.entries(files)) {
    const full = path.join(root, rel);
    await fs.mkdir(path.dirname(full), { recursive: true });
    await fs.writeFile(full, contents);
  }
  return root;
}

afterEach(async () => {
  while (created.length > 0) {
    await fs.rm(created.pop()!, { recursive: true, force: true });
  }
});

/** Una línea sola, larga, como escupe un bundler: sin saltos y sin espacios. */
function minifiedLine(): string {
  const parts: string[] = [];
  for (let i = 0; i < 400; i++) parts.push(`function f${i}(a,b){return a+b*${i}}`);
  return `!function(e,t){${parts.join(";")}}(window,document);\n`;
}

