describe("ingest-exclusion — marca de cabecera de código generado", () => {
  it("reconoce la marca de cada ecosistema que la publica", () => {
    const casos: Record<string, string> = {
      go: "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n",
      "go-stringer": "// Code generated by \"stringer -type=Pill\"; DO NOT EDIT.\n\npackage x\n",
      dotnet: "// <auto-generated />\nnamespace App { class C {} }\n",
      meta: "/* @generated */\nexport const T = 1;\n",
      "meta-bloque": "/**\n * @generated SignedSource<<abc>>\n */\nexport const T = 1;\n",
      protoc_py: "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\nclass A: pass\n",
      pelado: "// DO NOT EDIT\nexport const A = 1;\n",
      numeral: "# DO NOT EDIT: regenerar con `make api`\nclass A: pass\n",
      guion: "-- Automatically generated by schema-dump\nSELECT 1;\n",
      frase: "// This file was automatically generated by openapi-generator.\nexport const A = 1;\n",
      html: "<!-- Auto-generated by docgen -->\nexport const A = 1;\n",
    };
    for (const [nombre, texto] of Object.entries(casos)) {
      expect(excludedByContent(texto, false), nombre).toMatchObject({ reason: "generated-marker" });
    }
  });

  it("NO excluye prosa del usuario que MENCIONA la convención — el falso positivo medido", () => {
    // Éste es literalmente el caso que se llevó puesto a `ingest-exclusion.ts`
    // en la primera corrida de humo sobre `src/`: la marca aparece en el medio
    // de una oración, no arrancando una línea de cabecera.
    const prosa =
      "/**\n" +
      " * Detecta cabeceras de código generado. Donde hay un literal (`.pb.go`,\n" +
      " * `DO NOT EDIT`) es porque lo fija la herramienta, y también reconoce\n" +
      " * `@generated` de Meta.\n" +
      " */\nexport const X = 1;\n";
    expect(excludedByContent(prosa, false)).toBeNull();
  });

  it("NO excluye por advertencias escritas a mano que no declaran el archivo", () => {
    const casos: Record<string, string> = {
      "do not modify suelto": "// Do not modify this list without updating the parser.\nexport const A = 1;\n",
      "orden importa": "// The order below matters; do not edit it lightly when adding a case.\nexport const A = 1;\n",
      "generado en el medio": "export const A = 1;\n// el snapshot de abajo lo genera el script; do not edit\nexport const B = 2;\n",
    };
    for (const [nombre, texto] of Object.entries(casos)) {
      expect(excludedByContent(texto, false), nombre).toBeNull();
    }
  });

  it("la marca tiene que estar en la CABECERA: más abajo es una nota sobre un bloque", () => {
    const tarde = `${"export const A = 1;\n".repeat(60)}// Code generated by x. DO NOT EDIT.\n`;
    expect(excludedByContent(tarde, false)).toBeNull();
  });
});

describe("ingest-exclusion — minificado por forma", () => {
  it("excluye un bundle de una sola línea aunque el nombre no diga nada", () => {
    const veredicto = excludedByContent(minifiedLine(), false);
    expect(veredicto).toMatchObject({ reason: "minified-shape" });
    expect(veredicto!.detail).toMatch(/largo medio de línea/);
  });

  it("NO excluye código normal, ni siquiera con una línea larga aislada", () => {
    const normal = Array.from({ length: 200 }, (_, i) => `export const c${i} = ${i};`).join("\n");
    expect(excludedByContent(normal, false)).toBeNull();

    // Un blob embebido de 1500 caracteres sube el máximo pero no el promedio:
    // el criterio exige LAS DOS cosas justamente para no comerse este caso.
    const conBlob = `export const BLOB = "${"x".repeat(1500)}";\n${normal}`;
    expect(excludedByContent(conBlob, false)).toBeNull();
  });

  it("NO excluye un archivo de líneas largas pero sin ninguna línea de máquina", () => {
    // Promedio 150 (> 110) pero máximo 150 (< 1000): es Java con genéricos
    // largos, no salida de un minificador.
    const largo = Array.from({ length: 40 }, () => "x".repeat(150)).join("\n");
    expect(excludedByContent(largo, false)).toBeNull();
  });

  it("descarta la última línea cuando el texto viene cortado por el corte de lectura", () => {
    // Diez líneas normales y una undécima cortada a la mitad de algo enorme.
    // Sin el descarte, ese pedazo contaría como una línea de máquina.
    const cortado = `${"const a = 1;\n".repeat(10)}${"y".repeat(5000)}`;
    expect(excludedByContent(cortado, true)).toBeNull();
    // El mismo texto, si el archivo REALMENTE termina ahí, sí es una línea larga
    // de verdad… pero el promedio sigue mandando: 11 líneas, promedio ~460.
    expect(excludedByContent(cortado, false)).toMatchObject({ reason: "minified-shape" });
  });
});

describe("ingest-exclusion — classifyExclusion sobre archivos reales", () => {
  it("decide por nombre sin leer, y por contenido cuando el nombre no alcanza", async () => {
    const root = await makeTree({
      "api/service.pb.go": "package api\n",
      "api/kind.go": "// Code generated by stringer. DO NOT EDIT.\n\npackage api\n",
      "assets/app.a1b2c3.js": minifiedLine(),
      "src/main.go": 'package main\n\nfunc main() { println("hola") }\n',
    });
    const veredicto = async (rel: string) => classifyExclusion(path.join(root, rel), rel);

    expect(await veredicto("api/service.pb.go")).toMatchObject({ reason: "generated-name" });
    expect(await veredicto("api/kind.go")).toMatchObject({ reason: "generated-marker" });
    expect(await veredicto("assets/app.a1b2c3.js")).toMatchObject({ reason: "minified-shape" });
    expect(await veredicto("src/main.go")).toBeNull();
  });

  it("un archivo ilegible no se excluye por serlo — que falle el resto del pipeline", async () => {
    const root = await makeTree({ "src/main.go": "package main\n" });
    expect(await classifyExclusion(path.join(root, "no-existe.go"), "no-existe.go")).toBeNull();
  });
});

describe("collectFiles — la exclusión aplicada en la ingesta", () => {
  it("saca vendorizado, generado y minificado, y deja intacto el código del usuario", async () => {
    const root = await makeTree({
      // código del usuario, seis lenguajes
      "src/main.go": 'package main\n\nfunc main() { println("hola") }\n',
      "src/saludo.ts": "export function saludar(n: string) { return n; }\n",
      "src/caja.py": "class Caja:\n    def __init__(self, v):\n        self.v = v\n",
      "src/caja.rb": "class Caja\n  def initialize(v)\n    @v = v\n  end\nend\n",
      "src/Caja.cs": "namespace App { public class Caja { public int V; } }\n",
      "src/Caja.java": "package app;\npublic class Caja { public int v; }\n",
      // vendorizado por directorio (nombres agregados en D5)
      "third_party/upstream/leftpad.js": "export function leftPad(s) { return s; }\n",
      "deps/jason/lib/shim.js": "export const noop = () => {};\n",
      "obj/Debug/Temp.cs": "namespace App { class Temp {} }\n",
      "out/Build.java": "package app;\npublic class Build {}\n",
      // generado por nombre y por marca
      "api/service.pb.go": "package api\n\ntype Msg struct{ Id string }\n",
      "api/kind_string.go": "// Code generated by stringer. DO NOT EDIT.\n\npackage api\n",
      "api/Gen.cs": "// <auto-generated />\nnamespace App { class Gen {} }\n",
      // minificado por forma, con nombre inocente
      "assets/app.a1b2c3.js": minifiedLine(),
    });

    const excluidos: ExcludedFile[] = [];
    const quedaron = await collectFiles(root, { onExcluded: (e) => excluidos.push(e) });

    expect(quedaron.map((f) => f.path).sort()).toEqual([
      "src/Caja.cs",
      "src/Caja.java",
      "src/caja.py",
      "src/caja.rb",
      "src/main.go",
      "src/saludo.ts",
    ]);

    const porRuta = new Map(excluidos.map((e) => [e.path, e.reason]));
    expect(porRuta.get("api/service.pb.go")).toBe("generated-name");
    expect(porRuta.get("api/kind_string.go")).toBe("generated-marker");
    expect(porRuta.get("api/Gen.cs")).toBe("generated-marker");
    expect(porRuta.get("assets/app.a1b2c3.js")).toBe("minified-shape");
    // Los árboles se reportan por DIRECTORIO, no por archivo: adentro no se
    // entra, que es de dónde sale el ahorro.
    expect(porRuta.get("third_party")).toBe("dependency-tree");
    expect(porRuta.get("deps")).toBe("dependency-tree");
    expect(porRuta.get("obj")).toBe("dependency-tree");
    expect(porRuta.get("out")).toBe("dependency-tree");
  });

  it("sin el callback el resultado es el mismo — `onExcluded` no cambia qué entra", async () => {
    const root = await makeTree({
      "src/main.go": "package main\n",
      "api/service.pb.go": "package api\n",
    });
    const conCallback = await collectFiles(root, { onExcluded: () => {} });
    const sinCallback = await collectFiles(root);
    expect(sinCallback.map((f) => f.path)).toEqual(conCallback.map((f) => f.path));
    expect(sinCallback.map((f) => f.path)).toEqual(["src/main.go"]);
  });

  it("NO poda los directorios rechazados a propósito (`bin`, `packages`, `lib`)", async () => {
    // El motivo está escrito en `SKIP_DIRS`: son nombres que elige el
    // proyecto tanto como la herramienta, y podarlos saca fuente del usuario.
    const root = await makeTree({
      "bin/cli.js": "export function main() {}\n",
      "packages/core/src/index.ts": "export const x = 1;\n",
      "lib/helper.rb": "def helper; end\n",
    });
    const quedaron = await collectFiles(root);
    expect(quedaron.map((f) => f.path).sort()).toEqual([
      "bin/cli.js",
      "lib/helper.rb",
      "packages/core/src/index.ts",
    ]);
  });
});

