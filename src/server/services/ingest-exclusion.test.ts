/**
 * Tests de la exclusión de vendorizado/generado/minificado en la ingesta (D5).
 *
 * La forma de estos tests sigue el requisito del frente, que tiene dos mitades
 * asimétricas y por eso hay MÁS casos negativos que positivos:
 *
 *   · Que la exclusión DISPARE es lo fácil: un `.pb.go` es un `.pb.go`.
 *   · Que NO se lleve puesto código legítimo del usuario es el requisito duro,
 *     porque un falso positivo saca código del análisis EN SILENCIO. Así que
 *     cada criterio tiene su caso de control pegado al lado, y hay uno
 *     (`prosa que habla de la convención`) que salió de un falso positivo
 *     medido de verdad: la primera versión de este módulo se excluía a SÍ
 *     MISMA porque su docstring nombra `DO NOT EDIT` en el medio de una
 *     oración.
 *
 * El último bloque es una compuerta sobre las fixtures REALES del proyecto:
 * ninguna de las 101 de `tests/fixtures/patterns` ni de las 133 de
 * `tests/fixtures/patterns-positive` puede quedar excluida. Si alguien afloja
 * un criterio de más, se entera acá y no seis olas después mirando por qué el
 * censo bajó.
 */
